DATE_LINE_RE = re.compile(r"^\s*\d{4}/\d{1,2}/\d{1,2}\s*,\s*[\d۰-۹:]+\s*$")
NAME_LINE_RE = re.compile(r"^(.*?)(?:\((.*?)\))?\s*$")

def norm_fa(s: str) -> str:
    s = (s or "").strip()
    s = s.replace("ي", "ی").replace("ك", "ک").replace("\u200c", " ")
    s = s.replace("'", "").replace('"', "")
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"^(دکتر|د)\s+", "", s).strip()
    return s

def parse_doctors(raw: str):
    rows = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if DATE_LINE_RE.match(line):
            continue

        m = NAME_LINE_RE.match(line)
        if not m:
            continue

        name_part = (m.group(1) or "").strip()
        specialty = (m.group(2) or "").strip()

        # بعضی خطوط مثل "دکتر فاطمه بشیری" بدون پرانتز
        name_norm = norm_fa(name_part)
        if not name_norm:
            continue

        name_display = f"دکتر {name_norm}"
        rows.append({
            "doctor_name_display": name_display,
            "doctor_name_norm": name_norm,
            "specialty": specialty,
        })

    df = pd.DataFrame(rows)

    # dedupe: اگر یک نفر دوبار آمده (مثل فاطمه بشیری) نسخه‌ای که تخصص دارد نگه داریم
    df["has_spec"] = df["specialty"].apply(lambda x: 1 if isinstance(x, str) and x.strip() else 0)
    df = df.sort_values(["doctor_name_norm", "has_spec"], ascending=[True, False])
    df = df.drop_duplicates(subset=["doctor_name_norm"], keep="first").drop(columns=["has_spec"])

    # id تولیدی پایدار
    df = df.reset_index(drop=True)
    df.insert(0, "doctor_id", range(1001, 1001 + len(df)))
    return df

def main():
    df = parse_doctors(RAW_TEXT)
    out = Path("data/inputs/reference/doctors_reference.csv")
    out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out, index=False, encoding="utf-8-sig")
    print(f"Wrote {len(df)} doctors -> {out}")

if __name__ == "__main__":
    main()
